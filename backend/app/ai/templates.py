def counter_rationale(
    language: str,
    *,
    current: Decimal,
    suggested: Decimal,
    floor: Decimal | None,
    market: Decimal | None,
    accept_advised: bool,
    floor_driven: bool,
    floor_unreachable: bool = False,
) -> str:
    """Why the rules suggest this counter price (or accepting the current one)."""
    language = _lang(language)
    texts = _COUNTER[language]
    sentences = [texts["intro"].format(current=per_kg(language, current))]
    if floor is not None:
        sentences.append(texts["floor"].format(floor=per_kg(language, floor)))
    elif floor_unreachable:
        sentences.append(texts["no_floor_possible"])
    if market is not None:
        sentences.append(texts["market"].format(market=per_kg(language, market)))
    if accept_advised:
        if floor is not None and market is not None:
            sentences.append(texts["accept_full"])
        elif floor is not None:
            sentences.append(texts["accept_floor"])
        elif market is not None:
            sentences.append(texts["accept_market"])
        else:
            sentences.append(texts["accept_none"])
    else:
        suggested_text = per_kg(language, suggested)
        if floor_driven:
            key = "counter_floor"
        elif market is not None:
            key = "counter_market"
        else:
            key = "counter_no_market"
        sentences.append(texts[key].format(suggested=suggested_text))
    sentences.append(texts["close"])
    return " ".join(sentences)


