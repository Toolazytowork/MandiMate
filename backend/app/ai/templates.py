def _payment_when(language: str, days: int) -> str:
    language = _lang(language)
    if days <= 0:
        return {
            "en": "on delivery",
            "hi": "डिलीवरी पर",
            "te": "డెలివరీ సమయంలో",
            "kn": "ಡೆಲಿವರಿ ಸಮಯದಲ್ಲಿ",
            "ur": "ڈلیوری پر",
        }[language]
    if language == "en":
        return f"in {days} day" if days == 1 else f"in {days} days"
    if language == "hi":
        return f"{days} दिन में"
    if language == "kn":
        return f"{days} ದಿನದಲ್ಲಿ" if days == 1 else f"{days} ದಿನಗಳಲ್ಲಿ"
    if language == "ur":
        return f"{days} دن میں"
    return f"{days} రోజులో" if days == 1 else f"{days} రోజుల్లో"


