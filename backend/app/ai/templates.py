def match_explanation(language: str, proposal: schemas.MatchProposal, crop: str) -> str:
    """Why the proposed group of harvests is (or is not) a workable lot, and what is missing."""
    language = _lang(language)
    texts = _MATCH[language]
    selected = [candidate for candidate in proposal.candidates if candidate.proposed_kg > 0]
    values = {
        "count": len(selected),
        "selected": kg(language, proposal.selected_total_kg),
        "grade": proposal.grade,
        "crop": crop,
        "target": kg(language, proposal.target_quantity_kg),
        "shortfall": kg(language, proposal.shortfall_kg),
    }
    if not selected:
        sentences = [texts["none"].format(**values)]
    else:
        key = "feasible" if proposal.feasible else "short"
        sentences = [texts[key].format(**values)]
        items = [
            texts["item"].format(
                name=candidate.farmer_name,
                place=f"{candidate.village}{_comma(language)}" if candidate.village else "",
                distance=format_number(to_decimal(candidate.distance_km)),
                score=format_number(to_decimal(candidate.score)),
                kg=kg(language, candidate.proposed_kg),
            )
            for candidate in selected[:MAX_LISTED_CANDIDATES]
        ]
        if len(selected) > MAX_LISTED_CANDIDATES:
            items.append(texts["more"].format(count=len(selected) - MAX_LISTED_CANDIDATES))
        sentences.append(texts["selected"].format(items=_semicolon(language).join(items)))
        uninspected = sum(1 for candidate in selected if candidate.quality_status != "inspected")
        if uninspected:
            sentences.append(texts["uninspected"].format(count=uninspected))
    if proposal.excluded:
        reasons: list[str] = []
        for exclusion in proposal.excluded:
            if exclusion.reason not in reasons:
                reasons.append(exclusion.reason)
        sentences.append(
            texts["excluded"].format(
                count=len(proposal.excluded), reasons=_semicolon(language).join(reasons[:3])
            )
        )
    sentences.append(texts["rules"])
    return " ".join(sentences)


