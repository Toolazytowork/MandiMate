def _lang(language: str | None) -> str:
    return language if language in LANGUAGE_NAMES else "en"


def _capitalize(text: str) -> str:
    return text[:1].upper() + text[1:] if text else text


# ─────────────────────────────── Formatting ───────────────────────────────


def money(value: Any) -> str:
    return format_rupees(to_decimal(value))


def per_kg(language: str, value: Any) -> str:
    amount = money(value)
    return {
        "en": f"{amount}/kg",
        "hi": f"{amount} प्रति किलो",
        "te": f"కిలోకు {amount}",
        "kn": f"ಕಿಲೋಗೆ {amount}",
        "ur": f"{amount} فی کلو",
    }[_lang(language)]


def kg(language: str, value: Any) -> str:
    number = format_number(to_decimal(value))
    return {
        "en": f"{number} kg",
        "hi": f"{number} किलो",
        "te": f"{number} కిలోలు",
        "kn": f"{number} ಕಿಲೋ",
        "ur": f"{number} کلو",
    }[_lang(language)]


def kg_for(language: str, value: Any) -> str:
    number = format_number(to_decimal(value))
    return {
        "en": f"for {number} kg",
        "hi": f"{number} किलो पर",
        "te": f"{number} కిలోలకు",
        "kn": f"{number} ಕಿಲೋಗೆ",
        "ur": f"{number} کلو پر",
    }[_lang(language)]


def _comma(language: str) -> str:
    return "، " if language == "ur" else ", "


def _semicolon(language: str) -> str:
    return "؛ " if language == "ur" else "; "


def join_list(language: str, items: Sequence[str]) -> str:
    items = [item for item in items if item]
    if len(items) <= 1:
        return "".join(items)
    language = _lang(language)
    last = {"en": " and ", "hi": " और ", "te": " మరియు ", "kn": " ಮತ್ತು ", "ur": " اور "}[language]
    return _comma(language).join(items[:-1]) + last + items[-1]


def crop_label(crop: Any, language: str) -> str:
    """The crop's name in the language (catalogue names), lower-cased in English."""
    language = _lang(language)
    if language != "en":
        localized = getattr(crop, f"name_{language}", None)
        if localized:
            return str(localized)
    return str(crop.name).lower()


