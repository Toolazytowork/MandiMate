def _signed_phrase(texts: dict[str, str], prefix: str, value: Decimal) -> tuple[str, int]:
    if value > 0:
        return texts[f"{prefix}_more"].format(amount=money(value)), 1
    if value < 0:
        return texts[f"{prefix}_less"].format(amount=money(-value)), -1
    return texts[f"{prefix}_same"], 0


def deal_explanation(
    language: str,
    crop: str,
    options: schemas.SellingOptions,
    comparison: OptionComparison,
    counteroffer: schemas.CounterSuggestion | None,
) -> str:
    """Plain-language comparison of the best option with the runner-up and the baseline."""
    language = _lang(language)
    texts = _DEAL[language]
    best, runner, baseline = comparison.best, comparison.runner_up, comparison.baseline

    if best is None:
        if baseline is None:
            return f"{texts['no_options'].format(crop=crop)} {texts['close']}"
        return " ".join(
            [
                texts["baseline_only"].format(
                    crop=crop,
                    qty=kg(language, baseline.quantity_kg),
                    net_per_kg=per_kg(language, baseline.net_per_kg),
                    net_total=money(baseline.net_amount),
                ),
                texts["close"],
            ]
        )

    sentences = [
        texts["best"].format(
            option=_capitalize(option_label(language, best)),
            net_per_kg=per_kg(language, best.net_per_kg),
            net_total=money(best.net_amount),
            qty_for=kg_for(language, best.quantity_kg),
        )
    ]

    if runner is not None and comparison.net_diff_per_kg is not None:
        other = option_label(language, runner)
        if comparison.net_diff_per_kg == 0:
            sentences.append(texts["compare_equal"].format(other=other))
        else:
            price, price_sign = _signed_phrase(
                texts, "price", comparison.price_diff_per_kg or _ZERO
            )
            cost, cost_sign = _signed_phrase(texts, "cost", comparison.cost_diff_per_kg or _ZERO)
            # Paying more but costing more (or less and less) pull in opposite directions.
            opposite = price_sign != 0 and price_sign == cost_sign
            sentences.append(
                texts["compare"].format(
                    other=other,
                    price=price,
                    joiner=texts["but" if opposite else "and"],
                    cost=cost,
                    net=money(comparison.net_diff_per_kg),
                )
            )
            other_diff = comparison.other_diff_per_kg or _ZERO
            if other_diff > 0:
                sentences.append(texts["other_more"].format(amount=money(other_diff)))
            elif other_diff < 0:
                sentences.append(texts["other_less"].format(amount=money(-other_diff)))

    sentences.append(texts["payment"].format(when=_payment_when(language, best.payment_terms_days)))

    uplift = comparison.uplift_vs_baseline_per_kg
    if baseline is not None and uplift is not None:
        baseline_text = per_kg(language, baseline.net_per_kg)
        if uplift > 0:
            key, amount = "baseline_more", uplift
        elif uplift < 0:
            key, amount = "baseline_less", -uplift
        else:
            key, amount = "baseline_same", _ZERO
        sentences.append(texts[key].format(uplift=money(amount), baseline=baseline_text))

    if best.meets_min_price is not None and options.min_price_per_kg is not None:
        key = "min_meets" if best.meets_min_price else "min_below"
        sentences.append(texts[key].format(min=per_kg(language, options.min_price_per_kg)))

    estimated = estimated_line_keys(best)[:3]
    if estimated:
        names = [_LINE_NAMES[language][key] for key in estimated]
        sentences.append(texts["estimated"].format(lines=join_list(language, names)))
    if best.unresolved:
        items = [unresolved_text(language, item) for item in best.unresolved]
        sentences.append(texts["unresolved"].format(items=join_list(language, items)))

    if counteroffer is not None:
        current = to_decimal(counteroffer.current_price_per_kg)
        suggested = to_decimal(counteroffer.suggested_price_per_kg)
        if suggested > current:
            text = texts["counter"].format(suggested=per_kg(language, suggested))
            if counteroffer.floor_price_per_kg is not None:
                text += texts["counter_floor"].format(
                    floor=per_kg(language, counteroffer.floor_price_per_kg)
                )
            sentences.append(text)
        elif counteroffer.floor_price_per_kg is not None or (
            counteroffer.market_reference_per_kg is not None
        ):
            sentences.append(texts["counter_accept"].format(current=per_kg(language, current)))

    sentences.append(texts["close"])
    return " ".join(sentences)


