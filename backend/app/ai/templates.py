def insights_summary(language: str, balances: Sequence[tuple[str, schemas.CropBalance]]) -> str:
    """Narrative over per-crop supply/demand balances (``(crop label, balance)`` pairs)."""
    language = _lang(language)
    texts = _INSIGHTS[language]
    rows = [
        (label, balance)
        for label, balance in balances
        if balance.listed_kg > 0 or balance.demanded_kg > 0
    ]
    if not rows:
        return texts["empty"]
    rows.sort(key=lambda row: (-abs(row[1].gap_kg), row[0]))
    sentences: list[str] = []
    for label, balance in rows[:MAX_INSIGHT_CROPS]:
        values = {
            "crop": _capitalize(label),
            "listed": kg(language, balance.listed_kg),
            "demanded": kg(language, balance.demanded_kg),
            "gap": kg(language, abs(balance.gap_kg)),
        }
        sentence = texts[balance.signal].format(**values)
        avg, market = balance.avg_offer_price_per_kg, balance.market_modal_price_per_kg
        if avg is not None and market is not None:
            sentence += texts["price_both"].format(
                avg=per_kg(language, avg), market=per_kg(language, market)
            )
        elif avg is not None:
            sentence += texts["price_avg"].format(avg=per_kg(language, avg))
        elif market is not None:
            sentence += texts["price_market"].format(market=per_kg(language, market))
        sentences.append(sentence)
    shortages = [label for label, balance in rows if balance.signal == "shortage"][:3]
    surpluses = [label for label, balance in rows if balance.signal == "surplus"][:3]
    if shortages:
        sentences.append(texts["action_shortage"].format(crops=join_list(language, shortages)))
    if surpluses:
        sentences.append(texts["action_surplus"].format(crops=join_list(language, surpluses)))
    return " ".join(sentences)
